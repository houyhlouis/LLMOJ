#!/usr/bin/env node
/** Stage the upstream frontend with local static dependencies and deployment settings. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const frontend = path.join(root, 'packages/frontend');
const output = path.resolve(process.env.HYHOJ_PUBLIC_DIR || path.join(root, 'public'));
const siteName = process.env.OJ_SITE_NAME || 'LLMOJ';
const require = createRequire(path.join(frontend, 'package.json'));
const copy = (source, destination) => {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.cpSync(source, destination, { recursive: true });
};
const packageInfo = name => {
  const filename = require.resolve(`${name}/package.json`);
  return { directory: path.dirname(filename), version: JSON.parse(fs.readFileSync(filename)).version };
};
const stage = (name, mapping, cdnName = name) => {
  const { directory, version } = packageInfo(name);
  const destination = path.join(output, 'cdnjs', cdnName, version);
  for (const [source, target] of Object.entries(mapping)) copy(path.join(directory, source), path.join(destination, target));
  const noticeDirectory = path.join(output, 'licenses', name);
  fs.mkdirSync(noticeDirectory, { recursive: true });
  for (const entry of fs.readdirSync(directory)) {
    if (/^(?:license|licence|copying|notice|copyright)(?:[.-]|$)/i.test(entry)) {
      copy(path.join(directory, entry), path.join(noticeDirectory, entry));
    }
  }
  return { directory, version, destination };
};

fs.mkdirSync(output, { recursive: true });
// Match the paths generated by packages/frontend/vite.config.ts and its lazy loaders.
stage('react', { umd: 'umd' });
stage('react-dom', { umd: 'umd' });
stage('mobx', { 'dist/mobx.umd.production.min.js': 'mobx.umd.production.min.js' });
stage('axios', { 'dist/axios.min.js': 'axios.min.js' });
stage('noty', { 'lib/noty.min.js': 'noty.min.js', 'lib/noty.css': 'noty.min.css' });
stage('semantic-ui-react', { 'dist/umd/semantic-ui-react.min.js': 'semantic-ui-react.min.js' });
stage('fomantic-ui-css', { components: 'components', themes: 'themes' }, 'fomantic-ui');
const monaco = stage('monaco-editor', { min: 'min' });
stage('mathjax-full', { es5: 'es5' }, 'mathjax');
stage('prismjs', { components: 'components', plugins: 'plugins' }, 'prism');

// The npm twemoji package does not include the SVG image collection. Fetch the
// matching tagged archive once and retain it, so later rebuilds need no network.
const twemoji = packageInfo('twemoji');
const twemojiDest = path.join(output, 'cdnjs/twemoji', twemoji.version, 'svg');
if (!fs.existsSync(path.join(twemojiDest, '1f389.svg'))) {
  const cache = path.join(root, 'runtime/downloads');
  fs.mkdirSync(cache, { recursive: true });
  const archive = path.join(cache, `twemoji-${twemoji.version}.tar.gz`);
  if (!fs.existsSync(archive)) {
    const temporary = `${archive}.partial`;
    execFileSync('curl', ['--fail', '--location', '--retry', '3', '--output', temporary,
      `https://codeload.github.com/twitter/twemoji/tar.gz/refs/tags/v${twemoji.version}`], { stdio: 'inherit' });
    fs.renameSync(temporary, archive);
  }
  const extracted = path.join(cache, `twemoji-${twemoji.version}`);
  execFileSync('tar', ['-xzf', archive, '-C', cache,
    `twemoji-${twemoji.version}/assets/svg`, `twemoji-${twemoji.version}/LICENSE-GRAPHICS`]);
  copy(path.join(extracted, 'assets/svg'), twemojiDest);
  copy(path.join(extracted, 'LICENSE-GRAPHICS'), path.join(twemojiDest, '../LICENSE-GRAPHICS'));
}

// Some Fomantic distributions import Google Fonts. The frontend already bundles
// local Lato/fontsource fonts, so remove only external @imports from copied CSS.
function files(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const filename = path.join(directory, entry.name);
    return entry.isDirectory() ? files(filename) : [filename];
  });
}
for (const filename of files(path.join(output, 'cdnjs/fomantic-ui'))) {
  if (!filename.endsWith('.css')) continue;
  const original = fs.readFileSync(filename, 'utf8');
  const local = original
    .replace(/@import\s+(?:url\()?['"]?(?:https?:)?\/\/[^;]+;/g, '')
    .replaceAll('https://twemoji.maxcdn.com/v/latest/svg/', `/cdnjs/twemoji/${twemoji.version}/svg/`);
  if (local !== original) fs.writeFileSync(filename, local);
}
// Only the supported Chinese/English application locales are published.
for (const filename of files(monaco.destination)) {
  if (/\.nls\.ja(?:\.|$)/.test(path.basename(filename))) fs.rmSync(filename, { force: true });
}
// Keep the site without a favicon or logo and remove the retired quote source.
for (const name of ['favicon.ico', 'logo-website.min.svg', 'hitokoto.json']) {
  fs.rmSync(path.join(output, 'assets', name), { force: true });
}

// Deploy only quote data for which the operator has redistribution rights.
const quoteFile = process.env.HYHOJ_QUOTE_FILE;
if (quoteFile) copy(path.resolve(quoteFile), path.join(output, 'assets/hitokoto.json'));
copy(path.join(root, 'THIRD_PARTY_NOTICES.md'), path.join(output, 'licenses/THIRD_PARTY_NOTICES.md'));
copy(path.join(root, 'LICENSE'), path.join(output, 'licenses/LibreOJ-LICENSE'));

if (process.argv.includes('--assets-only')) {
  console.log('Offline dependency assets staged in ' + output);
  process.exit(0);
}
if (process.argv.includes('--build')) {
  const pnpm = process.env.PNPM_BINARY || 'pnpm';
  execFileSync(pnpm, ['--filter', '@libreoj/frontend', 'run', 'build'], {
    cwd: root, env: { ...process.env, NODE_OPTIONS: '--max-old-space-size=2300' }, stdio: 'inherit'
  });
}
const dist = path.join(frontend, 'dist');
if (!fs.existsSync(path.join(dist, 'index.html'))) throw new Error('Build the frontend first or pass --build.');
copy(dist, path.join(output, 'frontend'));
fs.rmSync(path.join(output, 'frontend/index.html'), { force: true });

// Render a single same-origin bootstrap. Do not install the upstream bootstrap
// CDN service worker: it was designed for a separate origin and corrupts cached
// same-origin API/static responses by mapping non-JavaScript paths to '/'.
const substitutions = {
  __public_path__: '/frontend',
  __default_title__: siteName,
  __api_endpoint__: '',
  __favicon__: '',
  __applogo__: null,
  __gravatar__: 'https://gravatar.com',
  __ghavatar__: 'https://github.com',
  __cdnjs__: '/cdnjs'
};
let html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
for (const [placeholder, value] of Object.entries(substitutions)) {
  const escaped = JSON.stringify(value).replaceAll('<', '\\u003c').replaceAll('>', '\\u003e').replaceAll('&', '\\u0026');
  html = html.replaceAll(placeholder, () => escaped);
}
if (Object.keys(substitutions).some(placeholder => html.includes(placeholder))) throw new Error('Unresolved bootstrap placeholder.');
fs.writeFileSync(path.join(output, 'index.html'), html);
fs.writeFileSync(path.join(output, 'sw.js'), `self.addEventListener('install',()=>self.skipWaiting());self.addEventListener('activate',e=>e.waitUntil(Promise.all([self.registration.unregister(),caches.delete('bootstrap')])));\n`);

const manifest = files(output).filter(filename => !filename.endsWith('/offline-manifest.json')).map(filename => ({
  path: path.relative(output, filename),
  size: fs.statSync(filename).size,
  sha256: crypto.createHash('sha256').update(fs.readFileSync(filename)).digest('hex')
}));
fs.writeFileSync(path.join(output, 'offline-manifest.json'), JSON.stringify({ site: siteName, files: manifest }, null, 2));
console.log(`${siteName} staged ${manifest.length} local files in ${output}`);
